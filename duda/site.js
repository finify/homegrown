    col.insertBefore(panel, col.querySelector('.dmNewParagraph, .shg-places__map-note'));
    var label = panel.querySelector('.shg-pmap__label');
    var wrap = panel.querySelector('.shg-pmap__frame');
    var open = panel.querySelector('.shg-pmap__open');
