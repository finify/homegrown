// Builds the hosted files the 123-reg (Duda) site links to, from the paste-in files in duda/.
//
//   public/duda/base.css    colours, type, buttons, leaf photos, lightbox, video hero, blog (all pages)
//   public/duda/header.css  header and menus, desktop/tablet/mobile
//   public/duda/footer.css  footer, desktop/tablet/mobile
//   public/duda/shop.css    the store
//   public/duda/contact.css the Contact & find us page (linked from that page's Head HTML only)
//   public/duda/about.css   the About us page (linked from that page's Head HTML only)
//   public/duda/home.css    the Home page (linked from that page's Head HTML only)
//   public/duda/site.js     phone menu, leaf-photo scroll reveal, shop bar, photo lightbox and video hero
//
// Duda's per-device CSS panels can't be used from a linked file, so rules are scoped by the
// class Duda puts on <body>: phones get body.dmMobileBody, everything else doesn't.
// Run: node scripts/build-duda.mjs   (also runs as part of `npm run build`)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const read = (p) => readFileSync(new URL(`../duda/${p}`, import.meta.url), 'utf8')
const out = (name, text) => {
  writeFileSync(new URL(`../public/duda/${name}`, import.meta.url), text)
  console.log(`public/duda/${name} (${(text.length / 1024).toFixed(1)} KB)`)
}
mkdirSync(new URL('../public/duda/', import.meta.url), { recursive: true })

const desktopOnly = (css) => css.replace(/html (body )?#dm /g, 'html body:not(.dmMobileBody) #dm ')
const mobileOnly = (css) => css.replace(/html (body )?#dm /g, 'html body.dmMobileBody #dm ')
const banner = (what) =>
  `/* Sunderland Home Grown redesign: ${what}.\n   Generated by scripts/build-duda.mjs from the files in duda/. Edit those, not this file. */\n`

// Split menu/after/3-css-all-devices.css into its numbered sections ("/* ---------- 4. Header ...")
const all = read('menu/after/3-css-all-devices.css')
const sections = {}
all.split(/(?=\/\* ---------- \d+\.)/).forEach((chunk) => {
  const m = chunk.match(/^\/\* ---------- (\d+)\./)
  if (m) sections[m[1]] = chunk
})
const missing = ['1', '2', '3', '4', '5', '6', '7'].filter((n) => !sections[n])
if (missing.length) throw new Error(`3-css-all-devices.css is missing section(s) ${missing.join(', ')}`)

// The phone menu snippet holds CSS and JS together; pull them apart
const menuSnippet = read('menu/after/7-mobile-menu-body-end.html')
const menuCss = menuSnippet.match(/<style>([\s\S]*?)<\/style>/)[1]
const menuJs = menuSnippet.match(/<script>([\s\S]*?)<\/script>/)[1]
const leafJs = read('menu/after/6-body-end-html.html').match(/<script>([\s\S]*?)<\/script>/)[1]
const shopBarJs = read('menu/after/9-shop-bar-body-end.html').match(/<script>([\s\S]*?)<\/script>/)[1]
const lightbox = read('menu/after/10-lightbox-body-end.html')
const lightboxCss = lightbox.match(/<style>([\s\S]*?)<\/style>/)[1]
const lightboxJs = lightbox.match(/<script>([\s\S]*?)<\/script>/)[1]
const video = read('menu/after/11-video-hero-body-end.html')
const videoCss = video.match(/<style>([\s\S]*?)<\/style>/)[1]
const videoJs = video.match(/<script>([\s\S]*?)<\/script>/)[1]
const placesJs = read('menu/after/12-places-body-end.html').match(/<script>([\s\S]*?)<\/script>/)[1]
const registerJs = read('menu/after/13-register-body-end.html').match(/<script>([\s\S]*?)<\/script>/)[1]

out('base.css', banner('base styles (colours, type, buttons, leaf photos)') +
  [sections['1'], sections['2'], sections['3'], sections['5'], sections['7'], '/* ===== Photo lightbox (site.js) ===== */\n' + lightboxCss, '/* ===== Video background hero (site.js) ===== */\n' + videoCss, '/* ===== Blog: landing page, post lists and single posts ===== */\n' + read('blog/after/blog.css'), '/* ===== Gallery page ===== */\n' + read('gallery/after/gallery.css'), '/* ===== Special thanks page ===== */\n' + read('thanks/after/thanks.css')].join('\n'))

out('header.css', banner('header and menus') + [
  sections['4'],
  '/* ===== Desktop and tablet ===== */\n' + desktopOnly(read('menu/after/4-css-desktop-and-tablet.css')),
  '/* ===== Mobile (Duda mobile layout) ===== */\n' + mobileOnly(read('menu/after/5-css-mobile.css')),
  '/* ===== Phone menu built by site.js ===== */\n' + menuCss,
].join('\n'))

out('footer.css', banner('footer') + [
  sections['6'],
  read('footer/after/css-all-devices.css'),
  '/* ===== Desktop and tablet ===== */\n' + desktopOnly(read('footer/after/css-desktop-and-tablet.css')),
  '/* ===== Mobile ===== */\n' + mobileOnly(read('footer/after/css-mobile.css')),
].join('\n'))

out('shop.css', banner('shop') + read('menu/after/8-css-shop.css'))

out('contact.css', banner('Contact & find us page') + read('contact/after/contact.css'))

out('about.css', banner('About us page') + read('about/after/about.css'))

out('home.css', banner('Home page') + read('home/after/home.css'))

out('day.css', banner('Day opportunities page') + read('day-opportunities/after/day.css'))

out('site.js', `/* Sunderland Home Grown redesign: phone menu and leaf-photo reveal.\n   Generated by scripts/build-duda.mjs. Edit duda/menu/after/6-*, 7-*, 9-*, 10-* and 11-*, not this file. */\n` +
  leafJs.trim() + '\n' + menuJs.trim() + '\n' + shopBarJs.trim() + '\n' + lightboxJs.trim() + '\n' + videoJs.trim() + '\n' + placesJs.trim() + '\n' + registerJs.trim() + '\n')
